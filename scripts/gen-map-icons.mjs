/**
 * Extracts the SVG of the icons drawn ON the map (MapLibre symbol images can't use CSS classes)
 * from the same Material Symbols set as the UI, into app/utils/mapIcons.generated.ts.
 * Run after changing POI_ICON / REPORT_ICON in app/utils/icons.ts:  npm run icons
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { getIconData, iconToSVG } from '@iconify/utils'

const set = JSON.parse(readFileSync(new URL('../node_modules/@iconify-json/material-symbols/icons.json', import.meta.url)))
const src = readFileSync(new URL('../app/utils/icons.ts', import.meta.url), 'utf8')

// semantic name → icon name, from the ICON registry
const registry = Object.fromEntries([...src.matchAll(/^\s+(\w+): 'icon-\[material-symbols--([a-z0-9-]+)\]'/gm)].map((m) => [m[1], m[2]]))
// semantic names used by the map markers (values of POI_ICON and REPORT_ICON)
const used = new Set()
for (const block of src.matchAll(/export const (?:POI_ICON|REPORT_ICON)[^{]*\{([^}]*)\}/g)) {
  for (const m of block[1].matchAll(/:\s*'(\w+)'/g)) used.add(m[1])
}

const out = {}
for (const name of [...used].sort()) {
  const icon = registry[name] && getIconData(set, registry[name])
  if (!icon) throw new Error(`Unknown icon for "${name}"`)
  const { attributes, body } = iconToSVG(icon, { height: 24 })
  out[name] = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${attributes.viewBox}" width="24" height="24" fill="currentColor">${body}</svg>`
}

writeFileSync(new URL('../app/utils/mapIcons.generated.ts', import.meta.url), `// Generated by scripts/gen-map-icons.mjs – do not edit. Run \`npm run icons\` to refresh.
/** SVG of the Material Symbols icons used as map markers, by ICON name. Colour via \`currentColor\`. */
export const MAP_ICON_SVG: Partial<Record<IconName, string>> = ${JSON.stringify(out, null, 2)}
`)
console.log(`map icons: ${Object.keys(out).join(', ')}`)
